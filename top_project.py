def execute_sql(sql):

    sql_upper = sql.upper().strip()

    if not sql_upper.startswith(
        "SELECT"
    ):
        return None, "Only SELECT queries are allowed."

    dangerous_words = [
        "INSERT",
        "UPDATE",
        "DELETE",
        "DROP",
        "ALTER",
        "CREATE",
        "TRUNCATE"
    ]

    for word in dangerous_words:

        if word in sql_upper:
            return None, (
                "Unsafe SQL operation detected."
            )

    try:

        result = pd.read_sql_query(
            sql,
            connection
        )

        return result, None

    except Exception as e:

        return None, str(e)

def sql_assistant(question):

    sql = generate_sql(
        question
    )

